// Rasterises Natural Earth land (public domain, via world-atlas) into the compact run-length land
// mask used by the "real world" map. Uses exact spherical point-in-polygon tests (d3-geo) so rings
// that wrap the antimeridian (Russia, Fiji...) are handled correctly. Takes about a minute.
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoBounds, geoContains } from 'd3-geo';

export const W = 400, H = 200, LAT_TOP = 82, LAT_BOTTOM = -58;
const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-50m.json', import.meta.url)));
const land = feature(topo, topo.objects.land);
const polys = land.features ? land.features : [land];

const parts = [];
for (const f of polys) {
  const g = f.geometry || f;
  const ps = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of ps) { const p = { type: 'Feature', geometry: { type: 'Polygon', coordinates: poly } }; p.bounds = geoBounds(p); parts.push(p); }
}
const bits = new Uint8Array(W * H);
for (let y = 0; y < H; y++) {
  const lat = LAT_TOP - (y + 0.5) * (LAT_TOP - LAT_BOTTOM) / H;
  const cands = parts.filter(p => lat >= p.bounds[0][1] && lat <= p.bounds[1][1]);
  for (let x = 0; x < W; x++) {
    const lon = -180 + (x + 0.5) * 360 / W;
    for (const p of cands) {
      const [[w0], [e0]] = p.bounds;
      const inLon = w0 <= e0 ? lon >= w0 && lon <= e0 : lon >= w0 || lon <= e0;
      if (inLon && geoContains(p, [lon, lat])) { bits[y * W + x] = 1; break; }
    }
  }
}
// run-length encode: alternating runs starting with water, base36 joined by ','
const runs = []; let cur = 0, n = 0;
for (const b of bits) { if (b === cur) n++; else { runs.push(n); cur = b; n = 1; } }
runs.push(n);
const out = `// Generated by scripts/build-earth.mjs from Natural Earth 1:50m land (public domain).\n` +
  `export const EARTH_W = ${W};\nexport const EARTH_H = ${H};\nexport const EARTH_LAT_TOP = ${LAT_TOP};\nexport const EARTH_LAT_BOTTOM = ${LAT_BOTTOM};\n` +
  `export const EARTH_RLE = '${runs.map(r => r.toString(36)).join(',')}';\n`;
writeFileSync(new URL('../src/sim/data/earth.ts', import.meta.url), out);
console.log('land tiles', bits.reduce((a, b) => a + b, 0), 'runs', runs.length);
